-- ---------------------------------------------------------------------
-- 1. 原始时序库（属性宽表 + 电芯聚合）：保留 365 天
--    DAYS 10   ：子表按 10 天分 vnode 文件
--    REPLICA 2 ：2 副本（raft 组，数据节点 ≥3）
--    VGROUPS 32：写入并行度，按节点数×4 调整，支持在线 rebalance
-- ---------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS iot_tsdb_raw
  KEEP      365
  DAYS      10
  BUFFER    256
  WAL_LEVEL 2
  FSYNC     0
  REPLICA   2
  VGROUPS   32
  PRECISION 'ms';

-- ---------------------------------------------------------------------
-- 2. 降采样聚合库：保留 1825 天（5 年）
--    承接 1m / 1h 聚合宽表，由连续查询写入
-- ---------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS iot_tsdb_agg
  KEEP      1825
  DAYS      30
  BUFFER    256
  WAL_LEVEL 2
  REPLICA   2
  VGROUPS   16
  PRECISION 'ms';

-- ---------------------------------------------------------------------
-- 3. 事件库：保留 30 天（事件量远小于属性；告警留存由 ES/MySQL 承担）
-- ---------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS iot_tsdb_event
  KEEP      30
  DAYS      10
  BUFFER    256
  WAL_LEVEL 2
  REPLICA   2
  VGROUPS   8
  PRECISION 'ms';

